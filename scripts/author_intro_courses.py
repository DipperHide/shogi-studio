def mate(prompt,pieces,accepted,explanation,hand='-'):
    s=move(prompt,pieces,accepted,explanation,hand)
    for usi in s['accepted']:
        b=shogi.Board(s['position']);b.push_usi(usi)
        assert b.is_checkmate(), (prompt,usi,b.sfen(),[m.usi() for m in b.legal_moves])
    return s

