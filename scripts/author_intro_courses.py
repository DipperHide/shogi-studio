def solo_line(pieces,moves,prompt,explanation):
    """Book movement tours deliberately omit enemy turns; independent exercises."""
    b=shogi.Board(pos(pieces)); out=[]
    for i,m in enumerate(moves.split()):
        b.turn=shogi.BLACK
        out.append(move(f'{prompt}（第 {i+1} 步）：走 {m}。',b.sfen(),m,explanation))
        b.push(shogi.Move.from_usi(m))
    return out

