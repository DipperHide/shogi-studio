def pos(pieces=None, hand='-', turn='b'):
    pieces = pieces or {}
    rows=[]
    for r in 'abcdefghi':
        line=''; empty=0
        for f in range(9,0,-1):
            v=pieces.get(str(f)+r)
            if v:
                if empty: line+=str(empty); empty=0
                line+=v
            else: empty+=1
        if empty: line+=str(empty)
        rows.append(line)
    return '/'.join(rows)+' '+turn+' '+hand+' 1'

def txt(body): return dict(kind='text', body=body)
def choice(prompt, options, answer, explanation): return dict(kind='choice', prompt=prompt, options=options, answer=answer, explanation=explanation)
def move(prompt,pieces,accepted,explanation,hand='-',turn='b',reply=None):
    s=dict(kind='move',prompt=prompt,position=pos(pieces,hand,turn) if isinstance(pieces,dict) else pieces,accepted=accepted.split(),explanation=explanation)
    if reply: s['reply']=reply.split()
    return s
def target(prompt,pieces,origin,targets,explanation): return dict(kind='targets',prompt=prompt,position=pos(pieces),**{'from':origin},targets=targets.split(),explanation=explanation)
def seq(prompt,position,moves,explanation,side=0): return dict(kind='sequence',prompt=prompt,position=position,moves=moves.split(),student_side=side,explanation=explanation)
