def solo_moves(position, entries, pages):
    """Book's one-sided assembly diagrams become separate legal move puzzles.

    No fictional opponent pass is introduced into the game rules or USI stream.
    """
    board = shogi.Board(position)
    steps = []
    for usi, prompt, explanation in entries:
        board.turn = shogi.BLACK
        steps.append(move(prompt, board.sfen(), usi, explanation, pages))
        parsed = shogi.Move.from_usi(usi)
        assert board.is_legal(parsed), (usi, board.sfen())
        board.push(parsed)
    board.turn = shogi.BLACK
    return steps, board.sfen()


