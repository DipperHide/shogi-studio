    replaced = set(data.get('replace_lesson_ids', data.get('replacement_lesson_ids', [])))
    if replaced:
        destination = next(c for c in BOOK['chapters'] if any(l['id'] in replaced for l in c['lessons']))
        insertion = next(i for i,l in enumerate(destination['lessons']) if l['id'] in replaced)
        destination['lessons'] = [l for l in destination['lessons'] if l['id'] not in replaced]
        destination['lessons'][insertion:insertion] = data['lessons']
    for lesson_id,steps in data.get('steps_by_lesson', {}).items():
        destination_lesson = next(l for c in BOOK['chapters'] for l in c['lessons'] if l['id'] == lesson_id)
        destination_lesson['steps'].extend(steps)
    for entry in data['coverage']:
        COVERAGE[entry['page']] = entry

