def pos(pieces, turn='b', hands='-'):
    """Explicit coordinates -> SFEN. Uppercase is sente; lowercase is gote."""
    board = [''] * 81
    for square, piece in pieces.items():
        board[(ord(square[1]) - 97) * 9 + 9 - int(square[0])] = piece
    rows = []
    for r in range(9):
        row, empty = '', 0
        for piece in board[r*9:r*9+9]:
            if not piece:
                empty += 1
            else:
                if empty:
                    row += str(empty)
                    empty = 0
                row += piece
        if empty:
            row += str(empty)
        rows.append(row)
    return '/'.join(rows) + f' {turn} {hands} 1'


def after(moves):
    board = shogi.Board()
    for move in moves.split():
        parsed = shogi.Move.from_usi(move)
        assert board.is_legal(parsed), (board.sfen(), move)
        board.push(parsed)
    return board.sfen()


def move(prompt, position, accepted, explanation, pages, reply=None):
    step = {'kind': 'move', 'prompt': prompt, 'position': position,
            'accepted': accepted.split(), 'explanation': explanation,
            'source_pages': pages}
    if reply:
        step['reply'] = reply.split()
    return step


